// De ondersteunde talen, in voorkeursvolgorde. Eén bron van waarheid voor de
// taaldetectie (initLocale) én de tests. We bieden nú alléén 'nl' aan: er is nog
// geen volledig 'en'-woordenboek, dus 'en' aanbieden zou de device-detectie naar
// een taal laten wijzen die niet bestaat. Zet 'en' hier pas terug zodra DICT.en
// compleet is (en t() valt tot die tijd sowieso terug op nl — zie hieronder).
export const SUPPORTED_LANGS = ['nl'];

const DEFAULT_LANG = 'nl';
let lang = DEFAULT_LANG;

// Abonnees voor taalwijziging (useSyncExternalStore in i18nRuntime leunt hierop).
// Een externe store i.p.v. React-context: t() blijft een gewone functie die ook
// in niet-component-code (lib, tests) werkt, terwijl de UI tóch herrendert.
const listeners = new Set();
const emit = () => { for (const l of listeners) l(); };

export function subscribeLang(listener) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

// Pure setter: wisselt de taal en notificeert. Persistentie zit bewust in de
// runtime-wrapper (setLanguage in i18nRuntime), niet hier — dit bestand blijft puur.
export function setLang(l) {
  if (DICT[l] && l !== lang) { lang = l; emit(); }
}

export function getLang() {
  return lang;
}

// Voor tests en latere talen: een (deel-)dictionary registreren of aanvullen.
export function registerDict(l, dict) {
  DICT[l] = { ...(DICT[l] ?? {}), ...dict };
}

// Het woordenboek van een taal (alleen-lezen gebruik in de pariteitstest).
export function getDict(l) {
  return DICT[l] ?? {};
}

// date-fns-locale voor de actieve taal. Schermen die datums formatteren vragen
// dit op i.p.v. `nl` hard te importeren, zodat datums meebewegen met de taal.
const DATE_LOCALES = { nl, en: enUS };
export function dateLocale() {
  return DATE_LOCALES[lang] ?? nl;
}

export function t(key, vars) {
  const table = DICT[lang] ?? {};
  let str = table[key];
  // Ontbreekt de sleutel in de actieve taal, val dan eerst terug op de default-taal
  // (nl) i.p.v. meteen op de kale sleutel — zo blijft de UI leesbaar bij een
  // (toekomstig) incompleet woordenboek. Pas als ook nl 'm mist tonen we de sleutel.
  if (str == null && lang !== DEFAULT_LANG) str = DICT[DEFAULT_LANG]?.[key];
  if (str == null) str = key; // zichtbare fallback: liever de sleutel dan leeg/crash
  if (vars) {
    str = str.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m));
  }
  return str;
}

// Eenvoudige pluralisatie: kies de 'één'- of 'meer'-sleutel op basis van n, en
// geef n als {n}-var door. Genoeg voor NL ("1 deelnemer" vs "3 deelnemers");
// til pas op naar ICU/intl als een taal met complexere regels echt komt.
export function plural(n, oneKey, otherKey, vars) {
  return t(n === 1 ? oneKey : otherKey, { n, ...vars });
}

// Vertaal een Supabase-auth-fout naar een nette NL-melding. Supabase levert z'n
// auth-fouten alléén in het Engels; hier mappen we de bekende gevallen op een
// i18n-sleutel zodat sign-in/sign-up/reset geen kale Engelse tekst tonen. Een
// onbekende fout valt terug op de ruwe boodschap (nog altijd zichtbaar/debugbaar),
// en een lege/ontbrekende fout op een generieke NL-melding.
// @param {unknown} error  Supabase-fout, string, of iets met een .message
export function authErrorMessage(error) {
  const raw = typeof error === 'string'
    ? error
    : (error && typeof error === 'object' && 'message' in error ? String(/** @type {any} */ (error).message ?? '') : '');
  const msg = raw.toLowerCase();
  if (!msg) return t('auth.err.generic');
  if (msg.includes('invalid login credentials')) return t('auth.err.invalidCredentials');
  if (msg.includes('email not confirmed')) return t('auth.err.emailNotConfirmed');
  if (msg.includes('already registered') || msg.includes('user already') || msg.includes('already been registered')) {
    return t('auth.err.userExists');
  }
  if (msg.includes('rate limit') || msg.includes('for security purposes') || msg.includes('too many requests')) {
    return t('auth.err.rateLimit');
  }
  if (msg.includes('password should be') || msg.includes('at least 6') || msg.includes('weak password')) {
    return t('auth.err.weakPassword');
  }
  // OTP-login (PLT-8): een verkeerde/verlopen inlogcode meldt Supabase als
  // "Token has expired or is invalid" (error.code: otp_expired/otp_disabled).
  if (msg.includes('token has expired') || msg.includes('otp')) {
    return t('auth.err.otpInvalid');
  }
  if (msg.includes('network') || msg.includes('failed to fetch') || msg.includes('fetch failed')) {
    return t('auth.err.network');
  }
  return raw;
}
